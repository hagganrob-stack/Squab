/**
 * Generates supabase/seed.sql from the demonstration dataset so the database
 * and the no-database fallback always contain identical sample content.
 *
 *   npm run seed:generate
 *
 * Sample stories/events are inserted with is_demo = true; remove them with:
 *   delete from stories where is_demo; delete from events where is_demo;
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { businesses, categories, events, homepageSettings, offers, stories } from "../src/lib/demo/data.ts";

type Value = string | number | boolean | null | undefined | string[] | object;

const lit = (v: Value): string => {
  if (v === null || v === undefined) return "null";
  if (typeof v === "boolean") return v ? "true" : "false";
  if (typeof v === "number") return String(v);
  if (Array.isArray(v)) return v.length ? `array[${v.map(lit).join(", ")}]::text[]` : "'{}'::text[]";
  if (typeof v === "object") return `${lit(JSON.stringify(v))}::jsonb`;
  return `'${v.replace(/'/g, "''")}'`;
};

const insert = (table: string, rows: Record<string, Value>[]) => {
  if (!rows.length) return "";
  const cols = Object.keys(rows[0]!);
  const values = rows.map((r) => `  (${cols.map((c) => lit(r[c])).join(", ")})`).join(",\n");
  return `insert into public.${table} (${cols.join(", ")}) values\n${values}\non conflict do nothing;\n\n`;
};

let sql = `-- GENERATED by scripts/generate-seed.ts — do not edit by hand.
-- Partners and offers are real (from the Squab Perks prototype); stories and
-- events are sample content flagged is_demo.

`;

sql += insert(
  "categories",
  categories.map((c, i) => ({ id: c.id, name: c.name, slug: c.slug, description: c.description, tone: c.tone, display_order: i })),
);

sql += insert(
  "businesses",
  businesses.map((b) => ({
    id: b.id,
    name: b.name,
    slug: b.slug,
    tagline: b.tagline,
    description: b.description,
    kind: b.kind,
    services: b.services,
    differentiator: b.differentiator,
    logo_url: b.logoUrl,
    logo_background: b.logoBackground ?? "light",
    cover_image_url: b.coverImageUrl,
    email: b.email,
    phone: b.phone,
    show_email: Boolean(b.email),
    show_phone: Boolean(b.phone),
    website: b.website,
    social_links: b.social,
    location: b.location,
    squab_connection: b.squabConnection,
    status: b.status,
    featured: b.featured,
    is_demo: b.isDemo,
  })),
);

sql += insert(
  "offers",
  offers.map((o) => ({
    id: o.id,
    business_id: o.businessId,
    title: o.title,
    slug: o.slug,
    short_description: o.shortDescription,
    full_description: o.fullDescription,
    what_you_get: o.whatYouGet,
    how_to_redeem: o.howToRedeem,
    image_url: o.imageUrl,
    reward_type: o.rewardType,
    reward_value: o.rewardLabel,
    redemption_method: o.redemptionMethod,
    redemption_url: o.redemptionUrl,
    redemption_code: o.redemptionCode,
    contact_email: o.contactEmail,
    contact_phone: o.contactPhone,
    terms: o.terms,
    start_date: o.startDate,
    expiry_date: o.expiryDate,
    status: o.status,
    featured: o.featured,
    is_demo: o.isDemo,
    created_at: o.createdAt,
    published_at: o.createdAt,
  })),
);

sql += insert(
  "stories",
  stories.map((s) => ({
    id: s.id,
    title: s.title,
    slug: s.slug,
    standfirst: s.standfirst,
    body: s.body,
    hero_image: s.heroImageUrl,
    hero_image_alt: s.heroImageAlt,
    author_name: s.authorName,
    category_id: s.categoryId,
    format: s.format,
    related_business_id: s.relatedBusinessId,
    status: s.status,
    featured: s.featured,
    is_demo: true,
    published_at: s.publishedAt,
  })),
);

sql += insert(
  "events",
  events.map((e) => ({
    id: e.id,
    title: e.title,
    slug: e.slug,
    summary: e.summary,
    description: e.description.join("\n\n"),
    what_to_expect: e.expect,
    who_should_attend: e.whoShouldAttend,
    image_url: e.imageUrl,
    start_datetime: e.startsAt,
    end_datetime: e.endsAt,
    time_tbc: e.timeTbc ?? false,
    venue: e.venue,
    address: e.address,
    registration_url: e.registrationUrl,
    contact_email: e.contactEmail,
    capacity: e.capacity,
    fully_booked: e.fullyBooked,
    status: e.status,
    featured: e.featured,
    is_demo: true,
  })),
);

sql += insert(
  "event_businesses",
  events.flatMap((e) => e.relatedBusinessIds.map((business_id) => ({ event_id: e.id, business_id }))),
);

sql += insert("site_settings", [{ key: "homepage", value: homepageSettings }]);

const out = fileURLToPath(new URL("../supabase/seed.sql", import.meta.url));
writeFileSync(out, sql);
console.log(`Wrote ${out}`);
